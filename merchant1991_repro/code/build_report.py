TITLE = "Reproduction of Merchant, Arnold, Baumgart, Mukherjee, Pein & Pinker (ISPSD 1991)"
SUB = '"Realization of High Breakdown Voltage (>700 V) in Thin SOI Devices"\nProc. ISPSD 1991, pp. 31-35'
A4 = (8.27, 11.69)


def text_page(pdf, title, blocks):
    """blocks: list of (kind, content), kind in {'h','t','m'}: header/text/math-ish."""
    fig = plt.figure(figsize=A4)
    fig.text(0.08, 0.95, title, fontsize=15, weight="bold", va="top")
    y = 0.89
    for kind, content in blocks:
        if kind == "h":
            y -= 0.008
            fig.text(0.08, y, content, fontsize=11.5, weight="bold", va="top")
            y -= 0.028
        elif kind == "m":
            fig.text(0.11, y, content, fontsize=11.5, va="top")
            y -= 0.05
        else:
            n = content.count("\n") + 1
            fig.text(0.08, y, content, fontsize=10.2, va="top", family="monospace",
                     linespacing=1.45)
            y -= 0.021 * n + 0.018
    pdf.savefig(fig)
    plt.close(fig)


def side_by_side(pdf, title, paper_png, model_png, caption=""):
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11.5, 6.0))
    for ax, png, lab in ((a1, paper_png, "Paper"), (a2, model_png, "Model")):
        img = mpimg.imread(png)
        ax.imshow(img)
        ax.axis("off")
        ax.set_title(lab, fontsize=11)
    fig.suptitle(title, fontsize=13, weight="bold")
    if caption:
        fig.text(0.5, 0.02, caption, ha="center", fontsize=9, wrap=True)
    fig.tight_layout(rect=(0, 0.04, 1, 0.95))
    pdf.savefig(fig)
    plt.close(fig)


def single_figure(pdf, title, png, caption=""):
    fig, ax = plt.subplots(figsize=(9.0, 6.4))
    ax.imshow(mpimg.imread(png))
    ax.axis("off")
    fig.suptitle(title, fontsize=13, weight="bold")
    if caption:
        fig.text(0.5, 0.02, caption, ha="center", fontsize=9, wrap=True)
    fig.tight_layout(rect=(0, 0.04, 1, 0.94))
    pdf.savefig(fig)
    plt.close(fig)


